import "server-only";

import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

import { APP } from "@/lib/constants";
import type { QuoteDto } from "@/features/quotes/types";

/** Rs 150,000 */
function formatPkr(amount: number): string {
  return `Rs ${new Intl.NumberFormat("en-PK").format(Math.round(amount))}`;
}

function formatDate(iso: string): string {
  return new Intl.DateTimeFormat("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
  }).format(new Date(iso));
}

const BRAND = rgb(0.2, 0.52, 0.27); // emerald-ish
const INK = rgb(0.1, 0.1, 0.12);
const MUTED = rgb(0.4, 0.42, 0.46);

/**
 * Builds a one-page, branded buy-back quote PDF for an approved offer.
 * Returns the raw bytes (base64-encode at the call site for email attachment).
 */
export async function buildQuotePdf(quote: QuoteDto, offerPricePkr: number): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const page = doc.addPage([595.28, 841.89]); // A4 portrait
  const { width, height } = page.getSize();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);

  const marginX = 48;
  let y = height - 64;

  const text = (
    value: string,
    opts: { x?: number; size?: number; font?: typeof font; color?: typeof INK } = {},
  ) => {
    page.drawText(value, {
      x: opts.x ?? marginX,
      y,
      size: opts.size ?? 11,
      font: opts.font ?? font,
      color: opts.color ?? INK,
    });
  };

  // Header
  text(APP.name, { size: 22, font: bold, color: BRAND });
  y -= 22;
  text("Phone Buy-Back Quote", { size: 13, font: bold, color: INK });
  y -= 16;
  text(`Quote ${quote.id}  ·  Issued ${formatDate(quote.createdAt)}`, {
    size: 10,
    color: MUTED,
  });

  // Divider
  y -= 18;
  page.drawLine({
    start: { x: marginX, y },
    end: { x: width - marginX, y },
    thickness: 1,
    color: rgb(0.88, 0.9, 0.92),
  });

  // Offer box
  y -= 40;
  page.drawRectangle({
    x: marginX,
    y: y - 18,
    width: width - marginX * 2,
    height: 72,
    color: rgb(0.95, 0.98, 0.96),
    borderColor: BRAND,
    borderWidth: 1,
  });
  text("Our offer for your device", { x: marginX + 16, size: 11, color: MUTED });
  y -= 30;
  text(formatPkr(offerPricePkr), { x: marginX + 16, size: 26, font: bold, color: BRAND });
  y -= 44;

  // Device details
  text("Device", { size: 12, font: bold });
  y -= 20;
  const rows: Array<[string, string]> = [
    ["Brand", quote.brand],
    ["Model", quote.model],
    ["Storage", quote.storage],
    ["PTA status", quote.ptaStatus],
    ["Offer valid until", formatDate(quote.validUntil)],
  ];
  for (const [label, value] of rows) {
    text(label, { size: 11, color: MUTED });
    text(value, { x: marginX + 160, size: 11, font: bold });
    y -= 18;
  }

  // Footer
  y = 96;
  page.drawLine({
    start: { x: marginX, y },
    end: { x: width - marginX, y },
    thickness: 1,
    color: rgb(0.88, 0.9, 0.92),
  });
  y -= 20;
  text(
    "This offer is subject to a physical inspection matching the details and photos you provided.",
    { size: 9, color: MUTED },
  );
  y -= 14;
  text(`Generated by ${APP.name}. Reply to this email to accept or ask a question.`, {
    size: 9,
    color: MUTED,
  });

  return doc.save();
}
